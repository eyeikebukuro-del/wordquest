export class KanjiDatabase {
  constructor() {
    /** 全漢字データ */
    this.words = this.buildKanjiEntries();
    /** カテゴリ一覧 */
    this.categories = [...new Set(this.words.map(w => w.category))];
  }

  /**
   * 漢字問題エントリ配列を構築
   * @returns {Array} 漢字オブジェクトの配列
   */
  buildKanjiEntries() {
    // 誤字（万が一の非日本語文字）を除外しつつ構築
    const validRaw = KANJI_RAW_DATA.filter(([k]) => !/[a-zA-Z\uAC00-\uD7AF]/.test(k));

    return validRaw.map(([kanji, reading, template, strokes, grade], index) => {
      const sentenceWithKanji = template.replace(`{${reading}}`, `【${kanji}】`);
      const sentenceWithKana = template.replace(`{${reading}}`, `【${reading}】`);

      // 難易度（1: 小1、2: 小2〜3、3: 小4）
      const difficulty = grade === 1 ? 1 : (grade <= 3 ? 2 : 3);
      const category = `kanji_g${grade}`;
      const emojiMap = { 1: '🌱', 2: '🌿', 3: '🥋', 4: '🐉' };

      return {
        id: 20001 + index,
        kanji,
        reading,
        template,
        sentenceWithKanji,
        sentenceWithKana,
        strokes,
        grade,
        // 既存システム互換プロパティ
        english: `${kanji}（${reading}）`,
        japanese: template.replace(`{${reading}}`, kanji),
        emoji: emojiMap[grade] || '🥋',
        category,
        difficulty,
        isKanji: true
      };
    });
  }

  /**
   * 難易度でフィルタリング
   * @param {number} maxDifficulty - 最大難易度（1-3）
   * @returns {Array}
   */
  getWordsByDifficulty(maxDifficulty) {
    return this.words.filter(w => w.difficulty <= maxDifficulty);
  }

  /**
   * カテゴリでフィルタリング
   * @param {string} category - カテゴリ名
   * @returns {Array}
   */
  getWordsByCategory(category) {
    return this.words.filter(w => w.category === category);
  }

  /**
   * フロアに応じた学年別の出題確率設定
   * （1F: 小1中心、2F: 小2〜3中心、3F: 小3〜4中心）
   * @param {number} floor - 現在のフロア番号（1-3）
   * @returns {Object} 各学年(1, 2, 3, 4)の選択確率重み
   */
  getFloorGradeProbabilities(floor) {
    const gradeProbs = {
      1: { 1: 90, 2: 10, 3: 0, 4: 0 },    // 1F: 小1が90%、小2が10%
      2: { 1: 10, 2: 50, 3: 40, 4: 0 },   // 2F: 小2〜小3が中心
      3: { 1: 0, 2: 15, 3: 45, 4: 40 },   // 3F: 小3〜小4が中心
      4: { 1: 0, 2: 5, 3: 35, 4: 60 }     // 4F: 小4が中心（60%）
    };
    return gradeProbs[floor] || gradeProbs[4];
  }

  /**
   * フロアに応じたランダムな漢字問題を1つ取得
   * @param {number} floor - 現在のフロア番号（1-3）
   * @param {Object} weights - スペースドレップ重み
   * @param {Array} excludeIds - 除外ID配列
   * @returns {Object}
   */
  getWeightedRandomWord(floor, weights = {}, excludeIds = []) {
    const probs = this.getFloorGradeProbabilities(floor);

    // 1. まず学年を確率抽選
    const totalProb = (probs[1] || 0) + (probs[2] || 0) + (probs[3] || 0) + (probs[4] || 0);
    let roll = Math.random() * totalProb;
    let selectedGrade = 1;
    for (const g of [1, 2, 3, 4]) {
      roll -= (probs[g] || 0);
      if (roll <= 0) {
        selectedGrade = g;
        break;
      }
    }

    // 2. 選ばれた学年の漢字プールからスペースドレップ重みで抽選
    let candidates = this.words.filter(
      w => w.grade === selectedGrade && !excludeIds.includes(w.id)
    );
    if (candidates.length === 0) {
      candidates = this.words.filter(w => !excludeIds.includes(w.id));
    }
    if (candidates.length === 0) return null;

    const weightedList = candidates.map(w => ({
      word: w,
      weight: weights[w.id] || 1
    }));

    const totalWeight = weightedList.reduce((sum, item) => sum + item.weight, 0);
    let random = Math.random() * totalWeight;

    for (const item of weightedList) {
      random -= item.weight;
      if (random <= 0) return item.word;
    }

    return candidates[candidates.length - 1];
  }

  /**
   * 例文つき4択問題を生成（「読み当て」と「漢字当て」の2パターン）
   * @param {Object} correctEntry - 正解の漢字エントリ
   * @param {string} questionType - 出題タイプ
   * @returns {Object} 問題データ
   */
  generateQuestion(correctEntry, questionType = 'en_to_jp') {
    // 50%で「読み当て（kanji_read）」、50%で「漢字当て（kanji_write）」
    const isReadingQuiz = questionType === 'en_to_jp';

    // 同じ学年から誤答候補を優先取得
    let sameGradePool = this.words.filter(
      w => w.id !== correctEntry.id &&
        w.grade === correctEntry.grade &&
        w.reading !== correctEntry.reading &&
        w.kanji !== correctEntry.kanji
    );

    if (sameGradePool.length < 3) {
      const otherPool = this.words.filter(
        w => w.id !== correctEntry.id &&
          w.reading !== correctEntry.reading &&
          w.kanji !== correctEntry.kanji
      );
      sameGradePool = [...sameGradePool, ...otherPool];
    }

    // 読み当ての場合は文字数が近い読みを優先するとより良い問題になる
    sameGradePool.sort((a, b) => {
      const diffA = Math.abs(a.reading.length - correctEntry.reading.length);
      const diffB = Math.abs(b.reading.length - correctEntry.reading.length);
      return (diffA - diffB) + (Math.random() - 0.5) * 2;
    });

    const wrongChoices = [];
    const usedValues = new Set([isReadingQuiz ? correctEntry.reading : correctEntry.kanji]);
    for (const item of sameGradePool) {
      const val = isReadingQuiz ? item.reading : item.kanji;
      if (!usedValues.has(val)) {
        usedValues.add(val);
        wrongChoices.push(item);
        if (wrongChoices.length >= 3) break;
      }
    }

    const allChoices = [...wrongChoices, correctEntry].sort(() => Math.random() - 0.5);
    const correctIndex = allChoices.findIndex(c => c.id === correctEntry.id);

    if (isReadingQuiz) {
      // 読み当て：例文の【漢字】の読みをひらがな4択から選ぶ
      return {
        question: correctEntry.sentenceWithKanji,
        questionEmoji: correctEntry.emoji,
        choices: allChoices.map(c => c.reading),
        correctIndex,
        word: correctEntry,
        type: 'kanji_read',
        grade: correctEntry.grade,
        strokes: correctEntry.strokes
      };
    } else {
      // 漢字当て：例文の【ひらがな】に入る漢字を4択から選ぶ
      return {
        question: correctEntry.sentenceWithKana,
        questionEmoji: correctEntry.emoji,
        choices: allChoices.map(c => c.kanji),
        correctIndex,
        word: correctEntry,
        type: 'kanji_write',
        grade: correctEntry.grade,
        strokes: correctEntry.strokes
      };
    }
  }

  /**
   * タイピング（読み入力）問題を生成
   * @param {Object} correctEntry - 正解の漢字エントリ
   * @returns {Object}
   */
  generateTypingQuestion(correctEntry) {
    return {
      question: correctEntry.sentenceWithKanji,
      questionEmoji: correctEntry.emoji,
      answer: correctEntry.reading,
      aliases: [correctEntry.kanji],
      hint: `${correctEntry.reading.length}もじのよみ`,
      word: correctEntry,
      type: 'typing',
      grade: correctEntry.grade,
      strokes: correctEntry.strokes
    };
  }
}
